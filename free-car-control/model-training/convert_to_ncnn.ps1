# Convert ONNX to NCNN (FP32)
# Usage example:
#   .\convert_to_ncnn.ps1 -OnnxPath artifacts/tiny_classifier_fp32.onnx `
#                         -OutParam artifacts/tiny_classifier_fp32.ncnn.param `
#                         -OutBin artifacts/tiny_classifier_fp32.ncnn.bin `
#                         -InputWidth 64 `
#                         -InputHeight 48

param(
    # Input ONNX path
    [string]$OnnxPath = "artifacts/tiny_classifier_fp32.onnx",
    # Output NCNN param path
    [string]$OutParam = "artifacts/tiny_classifier_fp32.ncnn.param",
    # Output NCNN bin path
    [string]$OutBin = "artifacts/tiny_classifier_fp32.ncnn.bin",
    # Input width/height (only used when fallback to pnnx)
    [int]$InputWidth = 64,
    [int]$InputHeight = 64,
    # Legacy square input size override (only used when fallback to pnnx and > 0)
    [int]$InputSize = 0
)

function Find-Tool {
    param([string]$Name)

    # 1) Try PATH
    $cmd = Get-Command $Name -ErrorAction SilentlyContinue
    if ($cmd) {
        return $cmd.Source
    }

    # 2) Try recursive search in current workspace
    $localHits = Get-ChildItem -Path . -Recurse -Filter $Name -ErrorAction SilentlyContinue
    if ($localHits) {
        if ($env:PROCESSOR_ARCHITECTURE -eq "AMD64") {
            $preferX64 = $localHits | Where-Object { $_.FullName -match "\\x64\\" } | Select-Object -First 1
            if ($preferX64) {
                return $preferX64.FullName
            }
        }
        if ($env:PROCESSOR_ARCHITECTURE -eq "ARM64") {
            $preferArm64 = $localHits | Where-Object { $_.FullName -match "\\arm64\\" } | Select-Object -First 1
            if ($preferArm64) {
                return $preferArm64.FullName
            }
        }
        return ($localHits | Select-Object -First 1).FullName
    }

    return $null
}

$onnx2ncnnPath = Find-Tool -Name "onnx2ncnn.exe"
$pnnxPath = Find-Tool -Name "pnnx.exe"
$effectiveInputWidth = $InputWidth
$effectiveInputHeight = $InputHeight
if ($InputSize -gt 0) {
    $effectiveInputWidth = $InputSize
    $effectiveInputHeight = $InputSize
}
if ($effectiveInputWidth -le 0 -or $effectiveInputHeight -le 0) {
    Write-Error "Invalid pnnx input shape: ${effectiveInputWidth}x${effectiveInputHeight}"
    exit 1
}

if ($onnx2ncnnPath) {
    & $onnx2ncnnPath $OnnxPath $OutParam $OutBin
    if ($LASTEXITCODE -ne 0) {
        Write-Error "onnx2ncnn conversion failed."
        exit $LASTEXITCODE
    }
}
elseif ($pnnxPath) {
    & $pnnxPath $OnnxPath inputshape=[1,3,$effectiveInputHeight,$effectiveInputWidth] fp16=0
    if ($LASTEXITCODE -ne 0) {
        Write-Error "pnnx conversion failed."
        exit $LASTEXITCODE
    }

    # pnnx output names follow input onnx basename, so we normalize to user paths
    $generatedParam = [System.IO.Path]::ChangeExtension($OnnxPath, ".ncnn.param")
    $generatedBin = [System.IO.Path]::ChangeExtension($OnnxPath, ".ncnn.bin")

    if (-not (Test-Path -LiteralPath $generatedParam)) {
        Write-Error "pnnx output not found: $generatedParam"
        exit 1
    }
    if (-not (Test-Path -LiteralPath $generatedBin)) {
        Write-Error "pnnx output not found: $generatedBin"
        exit 1
    }

    Move-Item -Force -LiteralPath $generatedParam -Destination $OutParam
    Move-Item -Force -LiteralPath $generatedBin -Destination $OutBin
}
else {
    Write-Error "Neither onnx2ncnn.exe nor pnnx.exe was found."
    exit 1
}

# Cleanup temporary files generated by pnnx
$onnxBase = [System.IO.Path]::GetFileNameWithoutExtension($OnnxPath)
$onnxDir = [System.IO.Path]::GetDirectoryName($OnnxPath)
if ([string]::IsNullOrWhiteSpace($onnxDir)) {
    $onnxDir = (Get-Location).Path
}

$tempFiles = @(
    [System.IO.Path]::Combine($onnxDir, "$onnxBase.pnnx.param"),
    [System.IO.Path]::Combine($onnxDir, "$onnxBase.pnnx.bin"),
    [System.IO.Path]::Combine($onnxDir, "$onnxBase.pnnx.onnx"),
    [System.IO.Path]::Combine($onnxDir, "$onnxBase.pnnxsim.onnx"),
    [System.IO.Path]::Combine($onnxDir, "${onnxBase}_pnnx.py"),
    [System.IO.Path]::Combine($onnxDir, "${onnxBase}_ncnn.py")
)

foreach ($temp in $tempFiles) {
    if (Test-Path -LiteralPath $temp) {
        Remove-Item -Force -LiteralPath $temp
    }
}

Write-Host "Conversion completed: $OutParam, $OutBin"
